async def generate_ai_questions(
    skill_name: str,
    question_count: int = 5,
    user_level: str = "intermediate"
) -> List[Dict[str, Any]]:
    """
    Generate quiz questions using AI (OpenRouter/LLM).
    Creates contextual, relevant questions based on the skill and user's level.
    """
    skill_context = SKILL_CONTEXTS.get(skill_name, f"General {skill_name} concepts")

    system_prompt = """You are an expert technical educator creating quiz questions for a skill development platform.
Generate multiple-choice quiz questions that test practical knowledge, not just theoretical facts.
Each question should have exactly 4 options with one clearly correct answer.
Include a brief explanation for why the correct answer is right.

IMPORTANT: Return your response as valid JSON in this exact format:
{
    "questions": [
        {
            "question_text": "The question here?",
            "options": ["Option A", "Option B", "Option C", "Option D"],
            "correct_answer_index": 0,
            "explanation": "The correct answer is A because...",
            "difficulty": "Easy/Medium/Hard"
        }
    ]
}

Make questions practical and relevant to real-world coding scenarios."""

    user_prompt = f"""Generate {question_count} multiple-choice quiz questions about {skill_name}.
Skill context: {skill_context}
User level: {user_level}

Create questions that:
1. Test practical understanding, not just memorization
2. Include realistic scenarios a developer might encounter
3. Have one clearly correct answer
4. Have plausible but incorrect distractors

Return only the JSON format specified."""

    try:
        result = await llm_client.extract_structured_json(
            messages=[{"role": "user", "content": user_prompt}],
            system_prompt=system_prompt
        )

        if result.get("error"):
            print(f"[Quiz AI] Error generating questions: {result['error']}")
            return []

        data = result.get("data", {})
        questions = data.get("questions", [])

        print(f"[Quiz AI] Generated {len(questions)} questions for {skill_name}")
        return questions

    except Exception as e:
        print(f"[Quiz AI] Exception generating questions: {e}")
        return []


