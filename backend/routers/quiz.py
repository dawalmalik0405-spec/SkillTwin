# =========================================================
# Pydantic Schemas
# =========================================================

class QuizOptionSchema(BaseModel):
    id: int
    text: str


class QuizQuestionSchema(BaseModel):
    id: str
    question_text: str
    options: List[QuizOptionSchema]
    difficulty: str
    skill_name: str


class QuizSubmissionSchema(BaseModel):
    question_id: str
    selected_answer_index: int


class QuizResultSchema(BaseModel):
    question_id: str
    is_correct: bool
    correct_answer_index: int
    explanation: Optional[str]


class QuizResponseSchema(BaseModel):
    questions: List[QuizQuestionSchema]
    total_questions: int
    passing_score: int  # Percentage required to pass
    generated_by: str = "ai"  # Indicates if generated by AI


class QuizValidationRequest(BaseModel):
    user_id: str
    task_id: str  # The roadmap task this quiz is for
    submissions: List[QuizSubmissionSchema]
    time_taken_seconds: Optional[int] = None


class QuizValidationResponse(BaseModel):
    passed: bool
    score_percentage: int
    correct_answers: int
    total_questions: int
    results: List[QuizResultSchema]
    task_unlocked: bool
    next_task_id: Optional[str] = None
    message: str


class SkillQuizStatusResponse(BaseModel):
    task_id: str
    skill_name: str
    is_unlocked: bool
    is_completed: bool
    best_score: Optional[int] = None
    total_quizzes_taken: int


