@router.post("/validate", response_model=QuizValidationResponse)
async def validate_quiz(
    payload: QuizValidationRequest,
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db)
):
    """
    Validate quiz answers and unlock next roadmap node if passed.
    User must score at least 70% to pass and unlock the next task.
    """
    task_id = payload.task_id

    # Derive the user from the bearer token; never trust a body-supplied user_id,
    # or any caller could mark another user's tasks complete.
    token_user_id = get_user_id_from_token(authorization)
    if not token_user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required to submit a quiz."
        )
    user_id = token_user_id

    if not payload.submissions:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="No answers submitted."
        )

    # Look up only the submitted questions instead of loading the whole table.
    submitted_ids = []
    for submission in payload.submissions:
        try:
            submitted_ids.append(uuid.UUID(submission.question_id))
        except (ValueError, AttributeError, TypeError):
            # Unparseable id — handled as unknown below (fails closed).
            continue

    question_map = {}
    if submitted_ids:
        rows = db.query(QuizQuestionModel).filter(
            QuizQuestionModel.id.in_(submitted_ids)
        ).all()
        question_map = {str(q.id): q for q in rows}

    # Validate each answer
    results = []
    correct_count = 0

    for submission in payload.submissions:
        question_id = submission.question_id
        selected = submission.selected_answer_index

        q = question_map.get(question_id)
        if q is not None:
            is_correct = selected == q.correct_answer_index

            results.append(QuizResultSchema(
                question_id=question_id,
                is_correct=is_correct,
                correct_answer_index=q.correct_answer_index,
                explanation=q.explanation
            ))

            if is_correct:
                correct_count += 1
        else:
            # Unknown question id — fail closed. Marking these correct is what
            # made every quiz auto-pass at 100% regardless of the answers given.
            results.append(QuizResultSchema(
                question_id=question_id,
                is_correct=False,
                correct_answer_index=-1,
                explanation="This question could not be verified, so it was marked incorrect."
            ))

    # Calculate score
    total_questions = len(results)
    score_percentage = int((correct_count / total_questions * 100)) if total_questions > 0 else 0
    passing_score = 70

    passed = score_percentage >= passing_score

    # If passed, mark task as completed and determine next task
    task_unlocked = False
    next_task_id = None

    if passed:
        # Mark current task as completed
        try:
            existing = db.query(TaskProgressModel).filter(
                TaskProgressModel.user_id == uuid.UUID(user_id),
                TaskProgressModel.task_id == task_id
            ).first()

            if existing:
                existing.is_completed = True
                existing.completed_at = datetime.utcnow()
            else:
                new_progress = TaskProgressModel(
                    user_id=uuid.UUID(user_id),
                    task_id=task_id,
                    is_completed=True,
                    completed_at=datetime.utcnow()
                )
                db.add(new_progress)

            # Determine next task
            next_task_id = _get_next_task_id(task_id)

            if next_task_id:
                task_unlocked = True

            db.commit()
        except Exception as e:
            db.rollback()
            print(f"[Quiz] Error updating progress: {e}")

    return QuizValidationResponse(
        passed=passed,
        score_percentage=score_percentage,
        correct_answers=correct_count,
        total_questions=total_questions,
        results=results,
        task_unlocked=task_unlocked,
        next_task_id=next_task_id,
        message=_get_pass_message(passed, score_percentage, next_task_id)
    )


def _get_next_task_id(current_task_id: str) -> Optional[str]:
    """Determine the next task in the roadmap sequence."""
    task_sequence = TASK_SEQUENCE

    try:
        current_index = task_sequence.index(current_task_id)
        if current_index < len(task_sequence) - 1:
            return task_sequence[current_index + 1]
    except ValueError:
        pass

    return None


def _get_pass_message(passed: bool, score: int, next_task: Optional[str]) -> str:
    """Generate user-friendly message based on quiz result."""
    if passed:
        if next_task:
            return f"🎉 Congratulations! You passed with {score}%! The next node has been unlocked."
        else:
            return f"🎉 Congratulations! You've completed the roadmap with {score}%!"
    else:
        return f"📚 You scored {score}%. You need 70% to pass. Review the resources and try again!"


