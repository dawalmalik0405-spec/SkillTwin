# =========================================================
# Quiz Generation Endpoint
# =========================================================

def _persist_and_format(
    db: Session,
    source_skill: str,
    questions: List[Dict[str, Any]],
    limit: int
) -> List[QuizQuestionSchema]:
    """
    Store questions and return them as API schemas.

    Persisting is what makes grading possible at all: /validate looks the
    question up by id to read its correct_answer_index, so an unsaved question
    cannot be graded. Rows are deduped on (skill_name, question_text) so repeat
    generations reuse the existing row instead of growing the table without
    bound. `source_skill` is the skill the questions are actually about and is
    what gets stored and returned.
    """
    formatted: List[QuizQuestionSchema] = []
    seen_ids = set()

    for q in questions:
        if len(formatted) >= limit:
            break

        raw_options = q.get("options", [])
        question_text = q.get("question_text", "Question?")
        correct_index = q.get("correct_answer_index", 0)

        # Discard malformed questions rather than storing an unanswerable one.
        if not raw_options or not isinstance(correct_index, int):
            continue
        if correct_index < 0 or correct_index >= len(raw_options):
            continue

        record = db.query(QuizQuestionModel).filter(
            QuizQuestionModel.skill_name == source_skill,
            QuizQuestionModel.question_text == question_text
        ).first()

        if record is None:
            record = QuizQuestionModel(
                skill_name=source_skill,
                question_text=question_text,
                options=raw_options,
                correct_answer_index=correct_index,
                explanation=q.get("explanation"),
                difficulty=q.get("difficulty", "Medium")
            )
            db.add(record)
            db.flush()  # populate record.id without ending the transaction
        else:
            # Keep the stored answer key in sync with the freshly generated text.
            record.options = raw_options
            record.correct_answer_index = correct_index
            record.explanation = q.get("explanation")

        # Never ship the same question id twice in one quiz or the score
        # denominator gets skewed.
        if str(record.id) in seen_ids:
            continue
        seen_ids.add(str(record.id))

        formatted.append(QuizQuestionSchema(
            id=str(record.id),
            question_text=question_text,
            options=[QuizOptionSchema(id=j, text=opt) for j, opt in enumerate(raw_options)],
            difficulty=record.difficulty or "Medium",
            skill_name=source_skill
        ))

    return formatted


def _questions_from_db(db: Session, skill_name: str, limit: int) -> List[QuizQuestionSchema]:
    """Read already-stored questions for a skill (the schema.sql seed bank)."""
    rows = db.query(QuizQuestionModel).filter(
        QuizQuestionModel.skill_name == skill_name
    ).order_by(func.random()).limit(limit).all()

    formatted: List[QuizQuestionSchema] = []
    for row in rows:
        options = row.options or []
        if not options:
            continue
        if row.correct_answer_index is None or row.correct_answer_index >= len(options):
            continue
        formatted.append(QuizQuestionSchema(
            id=str(row.id),
            question_text=row.question_text,
            options=[QuizOptionSchema(id=j, text=opt) for j, opt in enumerate(options)],
            difficulty=row.difficulty or "Medium",
            skill_name=row.skill_name
        ))
    return formatted


@router.get("/generate/{task_id}", response_model=QuizResponseSchema)
async def generate_quiz(
    task_id: str,
    question_count: int = Query(5, ge=3, le=10),
    user_level: str = Query("intermediate", description="User's skill level: beginner, intermediate, advanced"),
    authorization: Optional[str] = Header(None),
    db: Session = Depends(get_db)
):
    """
    Generate a quiz for a specific roadmap task using AI.
    Creates contextual questions based on the skill and user's level.
    """
    skill_name = _get_skill_for_task(task_id)

    print(f"[Quiz] Generating quiz for task: {task_id}, skill: {skill_name}, level: {user_level}")

    # 1. Preferred source: AI-generated questions for this exact skill.
    formatted_questions: List[QuizQuestionSchema] = []
    generated_by = "ai"

    if llm_client.is_configured:
        ai_questions = await generate_ai_questions(skill_name, question_count, user_level)
        if ai_questions:
            formatted_questions = _persist_and_format(
                db, skill_name, ai_questions, question_count
            )

    # 2. AI unavailable or unusable: reuse questions already stored for this
    #    skill (the seed bank, plus anything a previous generation saved). If
    #    the skill has no bank of its own, try its nearest neighbour -- those
    #    rows keep their own skill_name, so the quiz stays honestly labelled.
    if len(formatted_questions) < MIN_QUIZ_QUESTIONS:
        print(f"[Quiz] Using stored question bank for {skill_name}")
        stored = _questions_from_db(db, skill_name, question_count)
        if len(stored) < MIN_QUIZ_QUESTIONS:
            alias = FALLBACK_SKILL_ALIASES.get(skill_name)
            if alias:
                aliased = _questions_from_db(db, alias, question_count)
                if len(aliased) > len(stored):
                    stored = aliased
        if len(stored) > len(formatted_questions):
            formatted_questions = stored
            generated_by = "question_bank"

    # 3. Nothing stored either: use the hardcoded bank. get_fallback_questions
    #    reports which skill the questions are actually about, and that is what
    #    gets stored and shown -- an off-topic quiz is never relabelled as this
    #    skill, so it can't quietly certify knowledge it never tested.
    if len(formatted_questions) < MIN_QUIZ_QUESTIONS:
        source_skill, fallback = get_fallback_questions(skill_name)
        if fallback:
            print(f"[Quiz] Falling back to hardcoded {source_skill} questions for {skill_name}")
            fb_formatted = _persist_and_format(db, source_skill, fallback, question_count)
            if len(fb_formatted) > len(formatted_questions):
                formatted_questions = fb_formatted
                generated_by = "fallback"

    db.commit()

    if len(formatted_questions) < MIN_QUIZ_QUESTIONS:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                f"No quiz is available for {skill_name} right now. "
                "Question generation is temporarily unavailable - please try again shortly."
            )
        )

    return QuizResponseSchema(
        questions=formatted_questions,
        total_questions=len(formatted_questions),
        passing_score=70,
        generated_by=generated_by
    )


